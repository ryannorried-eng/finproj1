CREATE TABLE IF NOT EXISTS mlb_model_predictions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    game_id TEXT NOT NULL,
    game_date TEXT NOT NULL,
    home_team TEXT NOT NULL,
    away_team TEXT NOT NULL,
    commence_time TEXT,
    model_home_win_prob REAL,
    model_run_diff REAL,
    model_total_runs REAL,
    model_implied_home_odds INTEGER,
    market_home_ml INTEGER,
    market_away_ml INTEGER,
    market_spread REAL,
    market_total REAL,
    ml_edge REAL,
    total_edge REAL,
    model_spread_pick TEXT,
    confidence TEXT,
    data_source TEXT,
    actual_home_score INTEGER,
    actual_away_score INTEGER,
    home_win_correct INTEGER,
    total_correct INTEGER,
    settled_at TEXT,
    created_at TEXT DEFAULT (datetime('now')),
    UNIQUE(game_id)
);
